# -*- coding: utf-8 -*-
"""
Q2 trade-off search and resource-feasible scheduler.

Starts from the hard-deadline-feasible partition generated by heuristic.py,
then repeatedly merges two box groups and re-schedules all jobs. Each accepted
merge must preserve all medical and first-batch hard deadlines.

The default target of 22 trips is a working balanced point on the current
frontier; the full frontier is exported so the team can justify the trade-off
in the paper instead of claiming a single universal optimum.
"""

from __future__ import annotations

import itertools
from pathlib import Path
from typing import Dict, Iterable, List, Set

import pandas as pd

from .heuristic import (
    Box,
    Physics,
    Resource,
    charge_time,
    load_inputs,
    solve as build_initial_solution,
)


class Profile:
    def __init__(
        self,
        type_code: str,
        order,
        duration: float,
        energy: float,
        offsets: Dict[str, float],
        latest_start: float,
    ):
        self.type_code = type_code
        self.order = tuple(order)
        self.duration = duration
        self.energy = energy
        self.offsets = offsets
        self.latest_start = latest_start


def route_profile(
    type_code: str,
    box_ids: Set[str],
    box_map: Dict[str, Box],
    physics: Physics,
    types,
    max_services: int = 6,
):
    t = types[type_code]
    boxes = [box_map[x] for x in box_ids]

    if sum(b.mass for b in boxes) > t.max_payload + 1e-9:
        return None
    if sum(b.volume for b in boxes) > t.max_volume + 1e-12:
        return None

    services = sorted({b.service for b in boxes})
    if len(services) > max_services:
        return None

    best = None

    for order in itertools.permutations(services):
        by_service = {
            s: [b for b in boxes if b.service == s]
            for s in order
        }

        now = t.prep + t.load_per_box * len(boxes)
        payload = sum(b.mass for b in boxes)
        prev = "O01"
        energy = 0.0
        offsets: Dict[str, float] = {}

        for service in order:
            energy += physics.energy(
                type_code,
                prev,
                service,
                payload,
            )
            now += physics.flight_time(
                type_code,
                prev,
                service,
            )
            now += (
                t.hand_base
                + t.hand_per_box * len(by_service[service])
            )

            for box in by_service[service]:
                offsets[box.id] = now

            payload -= sum(
                b.mass for b in by_service[service]
            )
            prev = service

        energy += physics.energy(
            type_code,
            prev,
            "O01",
            0.0,
        )
        now += physics.flight_time(
            type_code,
            prev,
            "O01",
        )

        if energy > (1.0 - t.rho) * t.energy_use + 1e-9:
            continue

        latest_start = min(
            (
                b.hard_deadline - offsets[b.id]
                for b in boxes
                if b.hard_deadline is not None
            ),
            default=1e18,
        )

        if latest_start < -1e-9:
            continue

        intrinsic_tardiness = sum(
            b.priority
            * max(0.0, offsets[b.id] - b.expected)
            for b in boxes
        )

        score = (
            -latest_start,
            intrinsic_tardiness,
            now,
            energy,
        )

        profile = Profile(
            type_code=type_code,
            order=order,
            duration=now,
            energy=energy,
            offsets=offsets,
            latest_start=latest_start,
        )

        if best is None or score < best[0]:
            best = (score, profile)

    return None if best is None else best[1]


def all_profiles(
    group: Set[str],
    box_map: Dict[str, Box],
    physics: Physics,
    types,
):
    return [
        p
        for type_code in ("A", "B", "C")
        if (
            p := route_profile(
                type_code,
                group,
                box_map,
                physics,
                types,
            )
        )
        is not None
    ]


def schedule_groups(
    groups: List[Set[str]],
    box_map: Dict[str, Box],
    physics: Physics,
    types,
    drone_specs: Iterable[Resource],
    battery_specs: Iterable[Resource],
):
    jobs = []

    for index, group in enumerate(groups):
        profiles = all_profiles(
            group,
            box_map,
            physics,
            types,
        )
        if not profiles:
            return None

        hard_boxes = [
            box_map[x]
            for x in group
            if box_map[x].hard_deadline is not None
        ]
        hard_key = min(
            (b.hard_deadline for b in hard_boxes),
            default=1e18,
        )
        expected_key = min(
            box_map[x].expected for x in group
        )
        jobs.append(
            (
                index,
                group,
                profiles,
                hard_key,
                expected_key,
            )
        )

    jobs.sort(
        key=lambda z: (
            z[3],
            z[4],
            -sum(box_map[x].mass for x in z[1]),
        )
    )

    drones = {
        d.id: [d.type, 0.0]
        for d in drone_specs
    }
    batteries = {
        b.id: [b.type, 0.0]
        for b in battery_specs
    }

    schedule = []

    for index, ids, profiles, _hard_key, _expected_key in jobs:
        options = []

        for p in profiles:
            drone_id, drone_state = min(
                (
                    item
                    for item in drones.items()
                    if item[1][0] == p.type_code
                ),
                key=lambda x: x[1][1],
            )
            battery_id, battery_state = min(
                (
                    item
                    for item in batteries.items()
                    if item[1][0] == p.type_code
                ),
                key=lambda x: x[1][1],
            )

            start = max(
                drone_state[1],
                battery_state[1],
            )
            hard_miss = max(
                0.0,
                start - p.latest_start,
            )
            deliveries = {
                box_id: start + p.offsets[box_id]
                for box_id in ids
            }
            weighted_tardiness = sum(
                box_map[x].priority
                * max(
                    0.0,
                    deliveries[x] - box_map[x].expected,
                )
                for x in ids
            )

            options.append(
                (
                    (
                        hard_miss,
                        weighted_tardiness,
                        start + p.duration,
                        p.energy,
                    ),
                    p,
                    drone_id,
                    battery_id,
                    start,
                    deliveries,
                )
            )

        options.sort(key=lambda x: x[0])
        score, p, drone_id, battery_id, start, deliveries = options[0]

        if score[0] > 1e-7:
            return None

        end = start + p.duration
        soc = 1.0 - p.energy / types[p.type_code].energy_use

        drones[drone_id][1] = end
        batteries[battery_id][1] = (
            end
            + charge_time(
                types[p.type_code],
                soc,
            )
        )

        schedule.append(
            {
                "group": index,
                "ids": set(ids),
                "profile": p,
                "drone": drone_id,
                "battery": battery_id,
                "start": start,
                "end": end,
                "delivery": deliveries,
                "soc": 100.0 * soc,
            }
        )

    hard_violations = 0
    weighted_tardiness = 0.0

    for job in schedule:
        for box_id, delivery_time in job["delivery"].items():
            box = box_map[box_id]

            if (
                box.hard_deadline is not None
                and delivery_time
                > box.hard_deadline + 1e-7
            ):
                hard_violations += 1

            weighted_tardiness += (
                box.priority
                * max(
                    0.0,
                    delivery_time - box.expected,
                )
            )

    return {
        "jobs": schedule,
        "hard_violations": hard_violations,
        "weighted_tardiness": weighted_tardiness,
        "makespan": max(
            job["end"] for job in schedule
        ),
        "energy": sum(
            job["profile"].energy
            for job in schedule
        ),
        "trips": len(schedule),
    }


def merge_tradeoff_search(
    groups: List[Set[str]],
    box_map: Dict[str, Box],
    physics: Physics,
    types,
    drones,
    batteries,
    target_trips: int = 22,
):
    current = schedule_groups(
        groups,
        box_map,
        physics,
        types,
        drones,
        batteries,
    )
    if current is None:
        raise RuntimeError(
            "Initial Q2 partition cannot be scheduled."
        )

    frontier = [
        {
            "trips": current["trips"],
            "makespan": current["makespan"],
            "energy": current["energy"],
            "weighted_tardiness": current[
                "weighted_tardiness"
            ],
            "hard_violations": current[
                "hard_violations"
            ],
        }
    ]

    while len(groups) > target_trips:
        best = None

        for i in range(len(groups)):
            for j in range(i + 1, len(groups)):
                union = groups[i] | groups[j]

                if (
                    sum(box_map[x].mass for x in union)
                    > 80.0 + 1e-9
                ):
                    continue

                if (
                    sum(box_map[x].volume for x in union)
                    > 0.25 + 1e-12
                ):
                    continue

                if (
                    len(
                        {
                            box_map[x].service
                            for x in union
                        }
                    )
                    > 5
                ):
                    continue

                new_groups = [
                    group
                    for k, group in enumerate(groups)
                    if k not in (i, j)
                ] + [union]

                result = schedule_groups(
                    new_groups,
                    box_map,
                    physics,
                    types,
                    drones,
                    batteries,
                )
                if result is None:
                    continue

                balance_score = (
                    result["weighted_tardiness"] / 2e5
                    + result["makespan"] / 1e4
                    + result["energy"] / 100.0
                )

                candidate = (
                    balance_score,
                    i,
                    j,
                    new_groups,
                    result,
                )

                if (
                    best is None
                    or balance_score < best[0]
                ):
                    best = candidate

        if best is None:
            break

        _, _i, _j, groups, current = best
        frontier.append(
            {
                "trips": current["trips"],
                "makespan": current["makespan"],
                "energy": current["energy"],
                "weighted_tardiness": current[
                    "weighted_tardiness"
                ],
                "hard_violations": current[
                    "hard_violations"
                ],
            }
        )

    return groups, current, frontier


def export_solution(
    result,
    box_map: Dict[str, Box],
    out_dir: Path,
    frontier,
):
    out_dir.mkdir(parents=True, exist_ok=True)

    trip_rows = []
    box_rows = []

    ordered_jobs = sorted(
        result["jobs"],
        key=lambda x: (
            x["start"],
            x["drone"],
        ),
    )

    for index, job in enumerate(
        ordered_jobs,
        1,
    ):
        profile = job["profile"]
        trip_id = f"Q2-{index:03d}"

        trip_rows.append(
            {
                "架次编号": trip_id,
                "无人机编号": job["drone"],
                "机型编号": profile.type_code,
                "电池编号": job["battery"],
                "开始时刻（s）": job["start"],
                "访问服务区顺序": "->".join(
                    profile.order
                ),
                "返回O01时刻（s）": job["end"],
                "架次能耗（kWh）": profile.energy,
                "返航SOC（%）": job["soc"],
                "货箱数": len(job["ids"]),
                "货箱编号列表": ",".join(
                    sorted(job["ids"])
                ),
            }
        )

        for box_id, delivery_time in job[
            "delivery"
        ].items():
            box = box_map[box_id]
            box_rows.append(
                {
                    "货箱编号": box_id,
                    "架次编号": trip_id,
                    "服务区编号": box.service,
                    "交付完成时刻（s）": delivery_time,
                    "期望送达时间（s）": box.expected,
                    "硬截止时间（s）": box.hard_deadline,
                    "应急优先系数": box.priority,
                    "加权延误": (
                        box.priority
                        * max(
                            0.0,
                            delivery_time - box.expected,
                        )
                    ),
                }
            )

    pd.DataFrame(trip_rows).to_csv(
        out_dir / "Q2_transport_trips_balanced.csv",
        index=False,
        encoding="utf-8-sig",
    )
    pd.DataFrame(box_rows).sort_values(
        "货箱编号"
    ).to_csv(
        out_dir / "Q2_box_delivery_balanced.csv",
        index=False,
        encoding="utf-8-sig",
    )
    pd.DataFrame(frontier).to_csv(
        out_dir / "Q2_tradeoff_frontier.csv",
        index=False,
        encoding="utf-8-sig",
    )


def solve_q2(
    root: Path,
    out_dir: Path,
    target_trips: int = 22,
):
    initial = build_initial_solution(
        root,
        max_stops=3,
        verbose=False,
    )

    boxes = initial["boxes"]
    box_map = {
        box.id: box
        for box in boxes
    }

    groups = [
        {
            box_id
            for ids in trip.boxes_by_stop.values()
            for box_id in ids
        }
        for trip in initial["trips"]
    ]

    _nodes, types, drones, batteries, _boxes, _dem = load_inputs(root)
    physics = initial["physics"]

    groups, result, frontier = merge_tradeoff_search(
        groups,
        box_map,
        physics,
        types,
        drones,
        batteries,
        target_trips=target_trips,
    )

    export_solution(
        result,
        box_map,
        out_dir,
        frontier,
    )

    return {
        "groups": groups,
        "result": result,
        "frontier": frontier,
    }
